// Cấp ao L nuôi L con; cấp nhân vật cần 5·(L−1), ao tối đa (25 con) ở cấp nhân vật 120.
const pondLevels = Array.from({ length: 25 }, (_, i) => {
  const level = i + 1;
  return {
    level,
    capacity: level,
    requiredLevel: level === 1 ? 1 : 5 * (level - 1),
    goldCost: level === 1 ? 0 : Math.round((300 * Math.pow(level - 1, 1.6)) / 50) * 50,
  };
});

